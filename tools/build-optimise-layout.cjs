// Build-time only: run npm ci in tools/ once, then return to the repo root.
// Then: node tools/build-optimise-layout.cjs
// NODE_PATH may point to a separate development install of those packages.
// The browser consumes the generated module without a compiler or eval.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const acorn = require('acorn');
const scope = require('eslint-scope');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'app.js'), 'utf8').replace(/\r\n/g, '\n');
const ast = acorn.parse(source, {ecmaVersion:'latest', sourceType:'module', ranges:true});
const definitions = new Map(), imports = new Map();
for (const node of ast.body) {
  if (node.type === 'FunctionDeclaration') definitions.set(node.id.name, {code:source.slice(node.start,node.end), start:node.start});
  if (node.type === 'VariableDeclaration') for (const item of node.declarations) {
    if (item.id.type === 'Identifier') definitions.set(item.id.name, {code:node.kind+' '+source.slice(item.start,item.end)+';', start:item.start});
  }
  if (node.type === 'ImportDeclaration') for (const item of node.specifiers) {
    if (item.type !== 'ImportSpecifier') throw Error('Planner generator requires named imports');
    imports.set(item.local.name, {from:node.source.value, imported:item.imported.name});
  }
}
const overrides = new Set(['state','localStorage','sessionStorage','VARIANTS','DISPLAY_VARIANTS','kyberPreviewVerified','craftingEventMultiplier']);
const globals = new Set(['Object','Array','Set','Math','Number','Boolean','Map','String','JSON','undefined','Infinity','structuredClone']);
const needed = new Map(), usedImports = new Map();
function include(name) {
  if (overrides.has(name) || needed.has(name)) return;
  if (imports.has(name)) {usedImports.set(name,imports.get(name)); return;}
  if (!definitions.has(name)) {
    if (!globals.has(name)) throw Error('Planner depends on an unsnapshotted global: '+name);
    return;
  }
  const definition = definitions.get(name); needed.set(name,definition);
  const parsed = acorn.parse(definition.code,{ecmaVersion:'latest',sourceType:'module',ranges:true});
  const references = scope.analyze(parsed,{ecmaVersion:2022,sourceType:'module',optimistic:true}).globalScope.through;
  for (const reference of references) include(reference.identifier.name);
}
for (const name of ['prepareOptimiseWorkerJob','novaIconicPurchaseOptions']) include(name);
const hash = crypto.createHash('sha256').update(source).digest('hex');
const header = '// Generated by tools/build-optimise-layout.cjs; edit the planning functions in app.js.\n'+
  '// app.js SHA256: '+hash+'\n'+
  '// Each worker gets private profile state. No DOM, account access or profile writes.\n';
const importLines = [...usedImports].map(([name,item])=>`import { ${item.imported}${name===item.imported?'':' as '+name} } from '${item.from}';`).join('\n');
const factory = `\nexport function createOptimiseLayoutContext(input) {
const state = input.state;
const localStorage = {getItem:key=>input.storage[key]??null};
const sessionStorage = localStorage;
const VARIANTS = input.variants, DISPLAY_VARIANTS = input.displayVariants;
const kyberPreviewVerified = input.kyberPreviewVerified;
let craftingEventMultiplier = input.craftingEventMultiplier;
`;
const body = [...needed.values()].sort((a,b)=>a.start-b.start).map(item=>item.code).join('\n\n');
fs.writeFileSync(path.join(root,'optimise-layout-context.js'),header+importLines+'\n'+factory+body+'\nreturn {prepareOptimiseWorkerJob,novaIconicPurchaseOptions};\n}\n');
console.log('Generated isolated planner: '+needed.size+' shared declarations.');
